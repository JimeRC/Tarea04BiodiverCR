    private void mostrarResultados() {

    lbl_Intento1.setText("Intento 1: Sin realizar");
    lbl_Intento2.setText("Intento 2: Sin realizar");
    lbl_Intento3.setText("Intento 3: Sin realizar");

    int cantidad = controlador.obtenerCantidadIntentos();

    if (cantidad >= 1) {
        lbl_Intento1.setText("Intento 1: "
                + controlador.obtenerPuntajeIntento(0) + " de 3 puntos");
    }

    if (cantidad >= 2) {
        lbl_Intento2.setText("Intento 2: "
                + controlador.obtenerPuntajeIntento(1) + " de 3 puntos");
    }

    if (cantidad >= 3) {
        lbl_Intento3.setText("Intento 3: "
                + controlador.obtenerPuntajeIntento(2) + " de 3 puntos");
    }
}

